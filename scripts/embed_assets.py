#!/usr/bin/env python3
"""Write desktop/src/assets.gen.js: the page's typeface and the three scenes as data URLs.

The kit's build (esbuild) bundles JavaScript only, and a desktop plugin may not fetch files at run time,
so the binary assets in desktop/assets/ travel inside plugin.js as strings. Run after changing an asset:
    /usr/bin/python3 scripts/embed_assets.py
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "desktop" / "assets"
FILES = {"FONT_REGULAR": ("libre-caslon-text.ttf", "font/ttf"), "FONT_ITALIC": ("libre-caslon-text-italic.ttf", "font/ttf"),
         "SCENE_LIGHT": ("snow-light.jpg", "image/jpeg"), "SCENE_DARK": ("night-tide.jpg", "image/jpeg"),
         "SCENE_MARSH": ("quiet-marsh.jpg", "image/jpeg")}

lines = ["// Generated by scripts/embed_assets.py from desktop/assets/. Do not edit by hand.",
         "// Libre Caslon Text: SIL Open Font License 1.1 (desktop/assets/Libre-Caslon-Text-OFL.txt)."]
for name, (file, mime) in FILES.items():
    data = base64.b64encode((ASSETS / file).read_bytes()).decode("ascii")
    lines.append(f"export const {name} = 'data:{mime};base64,{data}'")
(ROOT / "desktop" / "src" / "assets.gen.js").write_text("\n".join(lines) + "\n", encoding="ascii")
print("desktop/src/assets.gen.js", sum(len(l) for l in lines) // 1024, "KB")
