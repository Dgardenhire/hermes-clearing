#!/usr/bin/env python3
"""Write desktop/src/assets.gen.js: the page's typeface as WOFF2 data URLs, and a manifest of the three scenes.

The kit's build (esbuild) bundles JavaScript only. The typeface travels inside plugin.js, compressed to WOFF2
(the same glyphs as the TTF in desktop/assets/), so the words never wait on anything to appear. The scene
photographs do not: the backend serves them through the plugin's own route (GET /scene/builtin/{name}), and
the page keeps a copy in its own data folder (ctx.files), so the bundle stays small. The manifest names each
scene's file, type and a short hash, so a changed photograph never shows from an old copy.

Run after changing an asset (needs fontTools with brotli, which macOS's /usr/bin/python3 has):
    /usr/bin/python3 scripts/embed_assets.py
"""
import base64
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "desktop" / "assets"
FONTS = {"FONT_REGULAR": "libre-caslon-text.ttf", "FONT_ITALIC": "libre-caslon-text-italic.ttf"}
# Kept in step with dashboard/plugin_api.py::SCENES (tests/test_scenes.py checks both).
SCENES = {"snow": ("snow-light.jpg", "image/jpeg"), "marsh": ("quiet-marsh.jpg", "image/jpeg"),
          "tide": ("night-tide.jpg", "image/jpeg")}


def woff2(path: Path) -> bytes:
    from fontTools.ttLib import TTFont
    font = TTFont(str(path))
    font.flavor = "woff2"
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def scene_hash(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()[:12]


def main():
    lines = ["// Generated by scripts/embed_assets.py from desktop/assets/. Do not edit by hand.",
             "// Libre Caslon Text: SIL Open Font License 1.1 (desktop/assets/Libre-Caslon-Text-OFL.txt)."]
    for name, file in FONTS.items():
        data = base64.b64encode(woff2(ASSETS / file)).decode("ascii")
        lines.append(f"export const {name} = 'data:font/woff2;base64,{data}'")
    manifest = {name: {"file": file, "mime": mime, "hash": scene_hash((ASSETS / file).read_bytes())}
                for name, (file, mime) in SCENES.items()}
    lines.append("// The scenes come from the backend (GET /scene/builtin/{name}); this is what to expect.")
    lines.append(f"export const SCENES = {json.dumps(manifest)}")
    (ROOT / "desktop" / "src" / "assets.gen.js").write_text("\n".join(lines) + "\n", encoding="ascii")
    print("desktop/src/assets.gen.js", sum(len(l) for l in lines) // 1024, "KB")


if __name__ == "__main__":
    main()
